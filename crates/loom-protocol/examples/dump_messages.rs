fn encode_pkg_version(v: &str) -> u32 {
    let parts: Vec<&str> = v.split('.').collect();
    assert_eq!(parts.len(), 3, "CARGO_PKG_VERSION must be major.minor.patch");
    let major: u32 = parts[0].parse().unwrap();
    let minor: u32 = parts[1].parse().unwrap();
    let patch: u32 = parts[2].parse().unwrap();
    (major << 24) | (minor << 16) | patch
}

fn hello_fixtures() -> Vec<ClientHello> {
    // All fixtures must satisfy `loom_session::names::validate_name`
    // — the server runs it before sending ServerHello and the TS
    // `validateClientHello` mirrors it. Earlier drafts included an
    // empty session name and a multi-byte UTF-8 name to stress the
    // length-prefix encoding; both are rejected by the validator, so
    // the wire-shape tests for them never reach the real handshake.
    vec![
        ClientHello {
            session_name: "main".into(),
            width: 1280,
            height: 720,
            cell_width: 9.5,
            cell_height: 18.0,
        },
        ClientHello {
            // 64-char name: max length, exercises the upper bound.
            session_name: "a".repeat(64),
            width: 800,
            height: 600,
            cell_width: 10.0,
            cell_height: 20.0,
        },
        ClientHello {
            // Digits + hyphen + lowercase: a "session-like" name from
            // `random_name()` style generators.
            session_name: "fresh-fox-12".into(),
            width: 1920,
            height: 1080,
            cell_width: 8.0,
            cell_height: 16.0,
        },
    ]
}

fn rmp_to_vec<T: Serialize + ?Sized>(value: &T) -> Vec<u8> {
    rmp_serde::to_vec(value).expect("encode")
}

fn hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

// ─── Naming helpers ─────────────────────────────────────────────────

fn snake_to_camel(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut upper_next = false;
    for c in s.chars() {
        if c == '_' {
            upper_next = true;
        } else if upper_next {
            for u in c.to_uppercase() {
                out.push(u);
            }
            upper_next = false;
        } else {
            out.push(c);
        }
    }
    out
}
